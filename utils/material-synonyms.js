// word(小写) → 所属词组
const INDEX = {};
GROUPS.forEach(group => {
  group.forEach(word => {
    const key = String(word).toLowerCase();
    if (!INDEX[key]) INDEX[key] = group;
  });
});

/**
 * 把一个查询 token 扩展成同义词集合（原 token 始终在第一位）。
 * @param {string} token
 * @returns {string[]}
 */
function expandToken(token) {
  const raw = String(token == null ? '' : token).trim();
  if (!raw) return [];
  const out = [raw];
  const group = INDEX[raw.toLowerCase()];
  if (group) {
    group.forEach(word => {
      if (word.toLowerCase() !== raw.toLowerCase()) out.push(word);
    });
  }
  return out;
}

